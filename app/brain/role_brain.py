def detect_role_class(job_role: str) -> tuple[str, str, str]:
    lowered = (job_role or "").lower()
    for role_class, keywords, mission in _ROLE_CLASSES:
        if any(kw in lowered for kw in keywords):
            return role_class, mission, role_class
    return "general", "Deliver high-quality engineering work in a fast-moving product team", "general"


def classify_seniority(job_role: str) -> str:
    lowered = (job_role or "").lower()
    if any(kw in lowered for kw in ("principal", "staff", "lead", "architect", "tech lead")):
        return "staff"
    if "senior" in lowered or "sr" in lowered:
        return "senior"
    if any(kw in lowered for kw in ("junior", "entry", "graduate", "intern", "trainee")):
        return "junior"
    if any(kw in lowered for kw in ("mid", "intermediate", "regular", "level")):
        return "mid"
    return "senior"


def _importance_for_competency(comp: dict, role_class: str) -> int:
    comp_id = str(comp.get("id") or "").lower()
    importance = _CANONICAL_IMPORTANCE.get(comp_id)
    if importance is None:
        category = str(comp.get("category") or "").lower()
        base = {"technical": 7, "cognitive": 7, "experience": 6, "behavioral": 5}.get(category, 5)
        boost = 0
        for keyword, delta in _ID_IMPORTANCE_BOOST.items():
            if keyword in comp_id:
                boost = max(boost, delta)
        importance = base + boost
    weight = float(comp.get("weight") or 1.0)
    if weight >= 3.0:
        importance = min(10, importance + 1)
    if weight <= 1.0 and importance > 5:
        importance = max(5, importance - 1)
    return max(1, min(10, importance))


def build_role_brain(
    *,
    job_role: str,
    taxonomy: list[dict] | None = None,
    required_competencies: list[str] | None = None,
    role_context: dict | None = None,
    company_brain: dict | None = None,
) -> dict:
    """Assemble the role intelligence brain.

    ``critical_competencies`` is the resolved taxonomy with importance and
    probe expectations — never a random LLM draw. The mission and emphasis come
    from the knowledge base, adapted by the role context (skills, description,
    tech stack) when present.
    """
    role_class, mission, label = detect_role_class(job_role)
    seniority = classify_seniority(job_role)
    taxonomy = taxonomy or []
    required_set = set(required_competencies or [])
    context = role_context or {}

    description = str(context.get("description") or "").lower()
    skills = [str(s).lower() for s in (context.get("skills_required") or [])]

    if role_class == "general" and description:
        mission = "Deliver high-quality engineering work for: " + description[:160]

    critical = []
    for comp in taxonomy:
        if not isinstance(comp, dict) or not comp.get("id"):
            continue
        comp_id = str(comp["id"])
        importance = _importance_for_competency(comp, role_class)
        if comp_id in required_set:
            importance = min(10, importance + 1)
        probe = str(comp.get("verification_probe") or "")
        if not probe:
            probe = default_probe_for(comp_id, role_class)
        critical.append(
            {
                "id": comp_id,
                "name": comp.get("name", comp_id),
                "importance": importance,
                "must_prove": probe,
                "category": comp.get("category", "general"),
            }
        )
    critical.sort(key=lambda c: c["importance"], reverse=True)

    return {
        "role": job_role,
        "class": label,
        "mission": mission,
        "seniority": seniority,
        "critical_competencies": critical,
        "level_expectations": {
            "senior": [
                "design independently",
                "mentor others",
                "handle ambiguity",
                "own production systems",
            ],
            "staff": [
                "define multi-system architecture",
                "set engineering standards",
                "influence org-wide decisions",
            ],
            "mid": ["design within a service", "own what you ship"],
            "junior": ["deliver with supervision", "grow fast"],
        }.get(seniority, ["design independently"]),
        "seniority_floor": {"junior": 1, "mid": 2, "senior": 3, "staff": 4}.get(seniority, 3),
        "emphasis_keywords": skills[:12] or (context.get("tech_stack") or [])[:12],
        "source": "knowledge_base",
    }


def default_probe_for(comp_id: str, role_class: str = "general") -> str:
    probes = {
        "tech_system_design": "Walk through a concrete architecture decision you owned, the tradeoffs you debated, and the failure you guarded against.",
        "tech_db": "Describe a database schema or query you optimized and how you reasoned about the tradeoff.",
        "tech_core": "Show me a hard bug in your core language you solved and how you debugged it.",
        "tech_event_driven": "Tell me about an event-driven flow you built: ordering, failure handling, idempotency.",
        "tech_deployment": "Walk me through shipping a change to production end to end.",
        "tech_caching": "Explain a caching decision you made and how you handled invalidation.",
        "behav_leadership": "Describe a time you led an engineering effort across teams.",
        "behav_communication": "Describe a technical tradeoff you had to explain to non-engineers.",
    }
    for keyword, probe in probes.items():
        if keyword in comp_id:
            return probe
    return "Walk me through a concrete example from your experience."